import type { WiringEntry } from "../../contracts/index.ts";

type BridgeHook = { handler: string; timeoutMs: number; failClosed: boolean };

type BridgeConfig = {
  command: string;
  args: string[];
  hooks: Record<string, BridgeHook>;
};

const CONFIG_PLACEHOLDER = "__TLC_BRIDGE_CONFIG__";

/**
 * why a generated plugin: OpenCode V2 runs plugins in-process and has no hook command of its own, so this file is
 * the only way a hook reaches the launcher. It speaks the same stdin/stdout contract every other host does, which
 * keeps the whole of core unaware that this host is different ([/decisions/ad-147.md](/decisions/ad-147.md)).
 *
 * invariant: plain JavaScript with no imports beyond Node built-ins — no `@opencode/plugin`, no `effect`. The file
 * lands in a config directory the harness does not own a `package.json` for, so a dependency could not resolve.
 *
 * hazard: `spawn`, never `spawnSync`. The plugin runs inside the OpenCode server, and a synchronous child would
 * stall every session on that server for as long as a hook runs.
 */
const BRIDGE_SOURCE = String.raw`// invariant: generated by tlc harness install (tlc-exec.mjs); the next install rewrites this file.
import { spawn } from "node:child_process";

const CONFIG = __TLC_BRIDGE_CONFIG__;

function runHook(hookEvent, payload) {
  const entry = CONFIG.hooks[hookEvent];
  if (!entry) {
    return Promise.resolve(null);
  }
  return new Promise((resolve) => {
    let settled = false;
    let timer;
    const finish = (value) => {
      if (!settled) {
        settled = true;
        clearTimeout(timer);
        resolve(value);
      }
    };
    let child;
    try {
      child = spawn(CONFIG.command, [...CONFIG.args, entry.handler], { stdio: ["pipe", "pipe", "ignore"] });
    } catch {
      finish(null);
      return;
    }
    timer = setTimeout(() => {
      child.kill();
      finish(null);
    }, entry.timeoutMs);
    let out = "";
    child.stdout.setEncoding("utf8");
    child.stdout.on("data", (chunk) => {
      out += chunk;
    });
    child.on("error", () => finish(null));
    child.on("close", () => {
      try {
        finish(JSON.parse(out.trim() || "null"));
      } catch {
        finish(null);
      }
    });
    child.stdin.on("error", () => {});
    child.stdin.end(JSON.stringify({ provider: "opencode", hook_event_name: hookEvent, ...payload }));
  });
}

function textOf(result) {
  const content = result ? result.content : undefined;
  if (typeof content === "string") {
    return content;
  }
  if (Array.isArray(content)) {
    return content
      .filter((part) => part && part.type === "text")
      .map((part) => part.text)
      .join("\n");
  }
  if (result && result.output !== undefined) {
    return typeof result.output === "string" ? result.output : JSON.stringify(result.output);
  }
  return "";
}

function withText(result, text) {
  return { ...result, content: [{ type: "text", text }] };
}

// why: a patch names its files inside its own text, so each one is checked as its own write.
function patchPaths(patchText) {
  const paths = [];
  for (const line of String(patchText || "").split("\n")) {
    const match = /^\*\*\* (?:Add File|Update File|Delete File|Move to): (.+)$/.exec(line.trim());
    if (match) {
      paths.push(match[1].trim());
    }
  }
  return paths;
}

function refusalFor(tool) {
  return new Error(
    "tlc harness did not answer for this " + tool + " call, and this hook fails closed. Run: tlc harness doctor",
  );
}

export default {
  id: "tlc-harness",
  async setup(ctx) {
    const directory = ctx.location ? ctx.location.directory : process.cwd();
    const sessionContext = new Map();

    await ctx.tool.hook("execute.before", async (event) => {
      // why: code mode wraps MCP calls in one execute call and fires this hook again for each inner call.
      if (event.tool === "execute") {
        return;
      }
      const base = { session_id: event.sessionID, call_id: event.id, tool: event.tool, directory };
      const isPatch = event.tool === "patch";
      const inputs = isPatch
        ? patchPaths(event.input && event.input.patchText).map((path) => ({ ...event.input, path }))
        : [event.input];
      if (inputs.length === 0) {
        inputs.push(event.input);
      }
      for (const input of inputs) {
        const reply = await runHook("tool.execute.before", { ...base, input });
        if (reply === null) {
          if (CONFIG.hooks["tool.execute.before"].failClosed) {
            throw refusalFor(event.tool);
          }
          continue;
        }
        if (reply.action === "deny") {
          throw new Error(reply.message);
        }
        if (reply.action === "rewriteInput" && !isPatch) {
          event.input = reply.input;
        }
      }
    });

    await ctx.tool.hook("execute.after", async (event) => {
      if (event.tool === "execute") {
        return;
      }
      const base = { session_id: event.sessionID, call_id: event.id, tool: event.tool, directory, input: event.input };
      if (event.status === "error") {
        await runHook("tool.execute.failed", { ...base, output: event.error ? event.error.message : "" });
        return;
      }
      const text = textOf(event.result);
      const reply = await runHook("tool.execute.after", { ...base, output: text });
      if (!reply) {
        return;
      }
      if (reply.action === "rewriteOutput") {
        event.result = withText(event.result, reply.content);
      } else if (reply.action === "context") {
        event.result = withText(event.result, text + "\n\n" + reply.text);
      }
    });

    await ctx.session.hook("context", async (event) => {
      if (!sessionContext.has(event.sessionID)) {
        const reply = await runHook("session.start", { session_id: event.sessionID, directory });
        sessionContext.set(event.sessionID, reply && reply.action === "context" ? reply.text : null);
      }
      const text = sessionContext.get(event.sessionID);
      if (text) {
        event.system.push({ type: "text", text });
      }
    });

    await ctx.session.hook("prompt", async (event) => {
      await runHook("session.prompt", {
        session_id: event.sessionID,
        prompt: event.prompt ? event.prompt.text : undefined,
        directory,
      });
    });
  },
};
`;

function bridgeConfigFor(entries: readonly WiringEntry[]): BridgeConfig {
  const first = entries[0];
  const hooks: Record<string, BridgeHook> = {};
  for (const entry of entries) {
    hooks[entry.hookEvent] = {
      handler: entry.handler,
      timeoutMs: entry.timeoutSeconds * 1000,
      failClosed: entry.failClosed === true,
    };
  }
  return {
    command: first?.command ?? "node",
    // invariant: every entry shares the launcher prefix; only the trailing handler differs, and the bridge appends it.
    args: first ? first.args.slice(0, -1) : [],
    hooks,
  };
}

export function renderBridge(entries: readonly WiringEntry[]): string {
  return BRIDGE_SOURCE.replace(CONFIG_PLACEHOLDER, JSON.stringify(bridgeConfigFor(entries), null, 2));
}
